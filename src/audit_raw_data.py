import pandas as pd

orders = pd.read_csv("data/raw/orders.csv")
print(orders.head())
print(orders.shape)
orders.info()
print(orders.isnull().sum())
print(orders.duplicated().sum())
missing_counts = orders.isnull().sum()
missing_percentage = (missing_counts / len(orders)) * 100
print(missing_percentage)
print(orders["status"].value_counts())
print(orders["order_id"].nunique())
print(pd.to_numeric(orders["order_amount"], errors = "coerce").isnull().sum())
print((orders["delivery_minutes"] < 0).sum())
print(orders["delivery_minutes"].isnull().sum())

customers = pd.read_csv("data/raw/customers.csv")
print(customers.head())
print(customers.shape)
customers.info()
print(customers.isnull().sum())
print(customers.duplicated().sum())
print((~customers["age"].between(10,100)).sum())
print(customers["city"].nunique())
print(customers["gender"].nunique())
print(customers["gender"].isnull().sum())

